import Foundation

/// 版本比较的回归测试。
///
/// 锁死一个很容易写错的地方：**版本号不能按字符串比**。
/// "3.10.0" 按字符串比会小于 "3.9.0"，于是一个真实的新版本会被判成旧版本，
/// 更新提示永远不出现 —— 而且这种错很难发现，因为大部分版本号恰好能比对。
@main
struct UpdateTest {
    static var failures = 0

    static func check(_ passed: Bool, _ message: String) {
        if passed {
            print("PASS: \(message)")
        } else {
            failures += 1
            print("FAIL: \(message)")
        }
    }

    static func main() {
        let c = UpdateChecker.compare

        check(c("3.2.0", "3.1.0") == 1, "3.2.0 > 3.1.0")
        check(c("3.1.0", "3.1.0") == 0, "3.1.0 == 3.1.0")
        check(c("3.0.1", "3.1.0") == -1, "3.0.1 < 3.1.0")

        // 关键用例：字符串比较会在这里出错（"10" < "9"）
        check(c("3.10.0", "3.9.0") == 1, "3.10.0 > 3.9.0（字符串比较会判反）")
        check(c("3.9.0", "3.10.0") == -1, "3.9.0 < 3.10.0（字符串比较会判反）")

        check(c("4.0.0", "3.99.99") == 1, "4.0.0 > 3.99.99")
        check(c("10.0.0", "9.9.9") == 1, "10.0.0 > 9.9.9")

        // 段数不齐时缺的段按 0 算
        check(c("3.1", "3.1.0") == 0, "3.1 == 3.1.0（缺段补 0）")
        check(c("3.1.1", "3.1") == 1, "3.1.1 > 3.1（缺段补 0）")

        // 带后缀的版本号：只取前缀数字，不因为 "-beta" 就崩掉
        check(c("3.1.0-beta", "3.1.0") == 0, "3.1.0-beta 与 3.1.0 同段（取数字前缀）")
        check(c("3.2.0-rc1", "3.1.9") == 1, "3.2.0-rc1 > 3.1.9")

        // 实际会遇到的场景：清单说 3.2.0，本地是 3.1.0 → 应该提示更新
        let online = "3.2.0", local = "3.1.0"
        check(c(online, local) > 0, "线上 \(online) 比本地 \(local) 新 → 提示更新")

        print(failures == 0 ? "\n全部通过" : "\n\(failures) 项失败")
        exit(failures == 0 ? 0 : 1)
    }
}
