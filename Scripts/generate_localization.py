#!/usr/bin/env python3
"""Generate the compiled UI catalog. Translation data never changes model identifiers."""
import json
import sys
from pathlib import Path
root = Path(__file__).resolve().parents[1]
data = json.loads((root/'Resources/Localization/en.json').read_text())
import re
for key,value in data.items():
    if set(re.findall(r'\{\d+\}',key)) != set(re.findall(r'\{\d+\}',value)):
        raise SystemExit('Placeholder mismatch: '+key)
    if re.findall(r'%(?:\.\d+)?[df@]',key) != re.findall(r'%(?:\.\d+)?[df@]',value):
        raise SystemExit('Format mismatch: '+key)
# Embed validated JSON in one raw literal. This avoids a large Swift dictionary
# expression while keeping tests and packaged apps independent of resource lookup.
encoded = json.dumps(data,ensure_ascii=False,sort_keys=True,indent=2)
assert '"""####' not in encoded
lines = ["// Generated by Scripts/generate_localization.py. Edit Resources/Localization/en.json.",
         "import Foundation", "enum LocalizationCatalog {",
         "    static let english: [String:String] = try! JSONDecoder().decode([String:String].self, from: Data(json.utf8))",
         '    private static let json = ####"""', encoded, '"""####', "}"]
path = root/'Sources/Phos/LocalizationCatalog.swift'
text='\n'.join(lines)+'\n'
if not path.exists() or path.read_text()!=text:
    if '--check' in sys.argv: raise SystemExit('LocalizationCatalog.swift is stale. Run Scripts/generate_localization.py.')
    path.write_text(text)
print(f'Validated {len(data)} UI translations')
